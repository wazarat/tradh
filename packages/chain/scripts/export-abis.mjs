// Copies the ABI of each Phase 1 contract from Foundry's `out/` into src/abis/*.ts as `as const`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "..", "contracts", "out");
const abiDir = join(here, "..", "src", "abis");
mkdirSync(abiDir, { recursive: true });

const contracts = ["MockStockToken", "MockUSD", "MockPriceOracle", "MockSpotExchange", "FeeController"];
const exportsList = [];
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(outDir, `${name}.sol`, `${name}.json`), "utf8"));
  const file = `${name}.ts`;
  writeFileSync(join(abiDir, file), `// Generated from packages/contracts/out/${name}.sol/${name}.json\nexport const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`);
  exportsList.push(`export { ${name}Abi } from "./${name}";`);
}
writeFileSync(join(abiDir, "index.ts"), `// Generated by scripts/export-abis.mjs. Do not edit by hand.\n${exportsList.join("\n")}\n`);
console.log(`exported ${contracts.length} ABIs`);
